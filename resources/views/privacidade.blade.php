            <h1>Política de Privacidade</h1>
            <p class="updated">Última atualização: 25 de setembro de 2026</p>

            <p>
                Esta política explica como a <strong>FSOFT Sistemas</strong>, inscrita no CNPJ
                <strong>60.177.690/0001-80</strong> ("FSOFT", "nós"), trata dados pessoais no <strong>SpeedNFE</strong>,
                incluindo o sistema web (speednfe.com.br) e o aplicativo SpeedNFE para iOS e Android, em conformidade
                com a Lei Geral de Proteção de Dados (Lei nº 13.709/2018 — LGPD).
            </p>

            <h2>1. Quais dados coletamos</h2>
            <ul>
                <li><strong>Dados da conta de usuário:</strong> nome, e-mail, senha (armazenada de forma criptografada) e perfil de acesso.</li>
                <li><strong>Dados da empresa cadastrada:</strong> razão social, nome fantasia, CNPJ/CPF, inscrição estadual, endereço, telefone, e-mail, regime tributário e o certificado digital (A1) usado para assinar os documentos fiscais, com a respectiva senha.</li>
                <li><strong>Dados cadastrados por você sobre terceiros:</strong> clientes/destinatários, fornecedores, motoristas e demais pessoas informadas nos documentos fiscais (nome, CPF/CNPJ, endereço, e-mail, telefone).</li>
                <li><strong>Dados fiscais e comerciais:</strong> produtos, notas fiscais (NF-e, NFC-e, MDF-e e demais documentos), valores, arquivos XML e DANFE.</li>
                <li><strong>Dados de pagamento da assinatura:</strong> informações das cobranças Pix. Não armazenamos dados de cartão de crédito.</li>
                <li><strong>Dados técnicos:</strong> endereço IP, data e hora de acesso e registros (logs) necessários para segurança e funcionamento do serviço.</li>
            </ul>

            <h2>2. Para que usamos os dados</h2>
            <ul>
                <li>Prestar o serviço contratado: emitir, transmitir, armazenar e consultar documentos fiscais eletrônicos e manter os cadastros do sistema (base legal: execução de contrato).</li>
                <li>Cumprir obrigações legais e regulatórias, como a guarda de documentos fiscais (base legal: cumprimento de obrigação legal).</li>
                <li>Autenticar usuários, prevenir fraudes e proteger a segurança do sistema (base legal: legítimo interesse).</li>
                <li>Prestar suporte e enviar comunicações sobre o serviço, como avisos de cobrança e de atualização.</li>
            </ul>
            <p>Não vendemos dados pessoais e não os usamos para publicidade.</p>

            <h2>3. Controlador e operador</h2>
            <p>
                A FSOFT é <strong>controladora</strong> dos dados da conta de usuário e da empresa contratante. Em relação aos dados
                que você cadastra sobre seus próprios clientes, fornecedores e demais terceiros, <strong>a sua empresa é a
                controladora</strong> e a FSOFT atua como <strong>operadora</strong>, tratando esses dados somente para prestar o serviço,
                conforme suas instruções.
            </p>

            <h2>4. Com quem compartilhamos</h2>
            <ul>
                <li><strong>Secretarias da Fazenda (SEFAZ), Receita Federal e demais órgãos fiscais:</strong> os documentos fiscais são transmitidos a esses órgãos para autorização, como exige a legislação.</li>
                <li><strong>Efí (Gerencianet):</strong> instituição de pagamento que processa as cobranças Pix.</li>
                <li><strong>ViaCEP e CNPJ.ws:</strong> serviços consultados para preencher automaticamente endereços e dados cadastrais. Recebem apenas o CEP ou o CNPJ consultado.</li>
                <li><strong>Provedores de infraestrutura:</strong> hospedagem, banco de dados e envio de e-mails, contratados para operar o serviço e sujeitos a obrigações de confidencialidade.</li>
                <li><strong>Autoridades públicas:</strong> quando houver obrigação legal ou ordem judicial.</li>
            </ul>

            <h2>5. Aplicativo móvel</h2>
            <ul>
                <li>O aplicativo acessa os mesmos dados da sua conta no SpeedNFE e não coleta dados adicionais.</li>
                <li>O aplicativo <strong>não</strong> usa rastreamento, publicidade, localização, câmera, microfone nem a sua lista de contatos.</li>
                <li>Se você marcar "lembrar de mim", o token de acesso fica guardado no armazenamento seguro do aparelho (Keychain no iOS e Keystore no Android). Ele é apagado ao sair da conta.</li>
                <li>Documentos que você baixa ou compartilha (XML e PDF) ficam no seu aparelho ou no aplicativo que você escolher.</li>
            </ul>

            <h2>6. Por quanto tempo guardamos</h2>
            <p>
                Mantemos os dados enquanto a conta estiver ativa. Documentos fiscais e os dados necessários à sua validade são
                guardados pelo prazo exigido pela legislação tributária (no mínimo 5 anos). Encerrado o contrato e cumpridos os prazos
                legais, os dados são excluídos ou anonimizados.
            </p>

            <h2>7. Segurança</h2>
            <p>
                Usamos conexão criptografada (HTTPS), senhas armazenadas com criptografia, controle de acesso por perfil de usuário e
                registros de acesso. Nenhum sistema é totalmente imune a incidentes. Se ocorrer um incidente que possa causar risco
                ou dano relevante aos titulares, comunicaremos os afetados e a Autoridade Nacional de Proteção de Dados (ANPD), como
                prevê a LGPD.
            </p>

            <h2>8. Seus direitos</h2>
            <p>Nos termos do art. 18 da LGPD, você pode solicitar:</p>
            <ul>
                <li>confirmação da existência de tratamento e acesso aos dados;</li>
                <li>correção de dados incompletos, inexatos ou desatualizados;</li>
                <li>anonimização, bloqueio ou eliminação de dados desnecessários ou tratados em desconformidade com a lei;</li>
                <li>portabilidade dos dados;</li>
                <li>informação sobre com quem os dados foram compartilhados;</li>
                <li>revogação do consentimento, quando o tratamento se basear nele.</li>
            </ul>
            <p>
                Os pedidos devem ser enviados para
                <a href="mailto:atendimento@f-softsistemas.com.br">atendimento@f-softsistemas.com.br</a>. Responderemos em até 15 dias.
                Pedidos sobre dados de clientes de uma empresa usuária são encaminhados a essa empresa, que é a controladora desses dados.
            </p>

            <h2>9. Exclusão da conta</h2>
            <p>
                Para excluir sua conta e seus dados, envie um pedido para
                <a href="mailto:atendimento@f-softsistemas.com.br">atendimento@f-softsistemas.com.br</a> a partir do e-mail cadastrado.
                Os dados serão eliminados, exceto os documentos fiscais e as informações que a lei nos obriga a manter pelo prazo legal.
            </p>

            <h2>10. Crianças e adolescentes</h2>
            <p>O SpeedNFE é um serviço destinado a empresas e não é direcionado a menores de 18 anos.</p>

